'use strict';
const assert = require('node:assert/strict');
const { compareVersions, selectRelease, checksumFor } = require('../src/updater');
const { installationTarget, windowsHelper } = require('../src/updater/install');
const asset = (name) => ({ name, browser_download_url: `https://github.com/Tikzen/CloudBerth/releases/download/v1.5.0/${name}`, size: 8 });
const release = (tag, names, options = {}) => ({ tag_name: tag, assets: names.map(asset), ...options });
const mac = ['CloudBerth-1.5.0-mac-arm64.zip', 'SHA256SUMS.txt'];
const win = ['CloudBerth-1.5.0-x64.exe', 'SHA256SUMS-windows.txt'];
assert.equal(compareVersions('v1.10.0', '1.9.9'), 1);
assert.equal(compareVersions('1.4.0-windows-test', '1.4.0'), 0);
assert.throws(() => compareVersions('bad', '1.0.0'));
const all = [release('v1.5.0-windows-test', win, { prerelease: true }), release('v1.5.0', mac)];
assert.equal(selectRelease(all, '1.4.0', 'darwin', 'arm64').tag, 'v1.5.0');
assert.equal(selectRelease(all, '1.4.0', 'win32', 'x64').tag, 'v1.5.0-windows-test');
assert.equal(selectRelease(all, '1.5.0', 'darwin', 'arm64'), null);
assert.equal(selectRelease(all, '1.4.0', 'darwin', 'x64'), null);
assert.equal(selectRelease([release('v1.5.0', mac, { draft: true })], '1.4.0', 'darwin', 'arm64'), null);
assert.equal(selectRelease([release('v1.5.0', mac, { prerelease: true })], '1.4.0', 'darwin', 'arm64'), null);
assert.equal(selectRelease([release('v1.5.0', [mac[0]])], '1.4.0', 'darwin', 'arm64'), null);
const evil = release('v1.5.0', mac); evil.assets[0].browser_download_url = 'https://evil.example/update.zip';
assert.equal(selectRelease([evil], '1.4.0', 'darwin', 'arm64'), null);
assert.equal(checksumFor('a'.repeat(64) + '  app.zip\n', 'app.zip'), 'a'.repeat(64));
assert.throws(() => checksumFor('a'.repeat(64) + '  wrong.zip', 'app.zip'));
assert.equal(installationTarget('darwin', '/Applications/CloudBerth.app/Contents/MacOS/CloudBerth'), '/Applications/CloudBerth.app');
assert.throws(() => installationTarget('darwin', '/Volumes/CloudBerth/CloudBerth.app/Contents/MacOS/CloudBerth'));
assert.throws(() => installationTarget('win32', 'unused', {}));
// Unusual path characters are encoded as data, never embedded as PowerShell expressions.
const helper = windowsHelper({ target: "C:\\a';$test\\CloudBerth.exe" });
assert(!helper.includes("C:\\a';$test"));
console.log('PASS: update version/platform selection, checksums, unsafe URLs and installation targets.');
