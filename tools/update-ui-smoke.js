'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { app, BrowserWindow, ipcMain } = require('electron');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'cloudberth-update-ui-'));
app.setPath('userData', temp); app.setPath('sessionData', temp);
const timer = setTimeout(() => { console.error('Update UI test timed out'); app.exit(1); }, 20000);
let window, cancelCount = 0, finishDownload;
let state = { status: 'idle', currentVersion: '1.4.0', trigger: 'manual', skippedVersion: '' };
const library = { games: [], shortcuts: { home: 'Shift+Meta+H', toggleDisplay: 'Shift+Meta+F', quit: 'Meta+Q' }, runningGameIds: [] };
ipcMain.handle('launcher:get-state', () => library);
ipcMain.handle('updates:get-state', () => state);
const send = (patch) => { state = { ...state, ...patch }; window.webContents.send('updates:changed', state); return state; };
ipcMain.handle('updates:check', () => send({ status: 'available', release: { version: '1.5.0', tag: 'v1.5.0', notes: '<img src=x onerror=alert(1)>更新说明', size: 1024 } }));
ipcMain.handle('updates:download', () => {
 send({ status: 'downloading', received: 512, total: 1024, progress: .5 });
 return new Promise((resolve) => { finishDownload = resolve; });
});
ipcMain.handle('updates:cancel', () => { cancelCount++; send({ status: 'available' }); finishDownload(state); return state; });
ipcMain.handle('updates:skip', () => send({ skippedVersion: state.release.tag }));
app.whenReady().then(async () => {
 window = new BrowserWindow({ show: false, width: 1280, height: 760, webPreferences: { preload: path.join(__dirname, '../src/preload.js'), sandbox: true, contextIsolation: true } });
 const js = (code) => window.webContents.executeJavaScript(code, true);
 await window.loadFile(path.join(__dirname, '../src/launcher/index.html'));
 await js('window.cloudBerth.updates.getState()');
 await js('document.querySelector("#updateButton").click()');
 await new Promise((r) => setTimeout(r, 150));
 assert(await js('document.querySelector("#updateDialog").open'));
 assert.equal(await js('document.querySelector("#updateNotes img")'), null);
 await js('document.querySelector("#updatePrimary").click()');
 await new Promise((r) => setTimeout(r, 150));
 assert.equal(await js('document.querySelector("#updateProgress").value'), .5);
 await js('document.querySelector("#updateCancel").click()');
 await new Promise((r) => setTimeout(r, 150));
 assert.equal(cancelCount, 1, 'Cancel must work while download IPC is awaiting completion');
 send({ status: 'ready', progress: 1 });
 await new Promise((r) => setTimeout(r, 80));
 assert.equal(await js('document.querySelector("#updatePrimary").textContent'), '重启并更新');
 fs.mkdirSync(path.join(__dirname, '../tmp'), { recursive: true });
 fs.writeFileSync(path.join(__dirname, '../tmp/update-dialog.png'), (await window.webContents.capturePage()).toPNG());
 window.destroy(); clearTimeout(timer); console.log('PASS: update dialog, safe release notes, download progress, active cancellation and restart state.'); app.exit(0);
}).catch((error) => { console.error(error); app.exit(1); });
